/// <reference types="vite/client" />
import { afterEach, describe, expect, it, vi } from "vitest";
import { convexTest } from "convex-test";
import type { FunctionReturnType } from "convex/server";
import aggregateTest from "@convex-dev/aggregate/test";
import schema from "./schema";
import { api, internal } from "./_generated/api";
import { findPrimaryNode } from "./orgTreeShared";

const modules = import.meta.glob("./**/*.ts");
const identity = { subject: "s11-delete-reader", email: "s11-delete@example.test", emailVerified: true };
afterEach(() => vi.useRealTimers());

describe("S11 workspace deletion continuation", () => {
  it("moves every child across the existing 20-child boundary and survives duplicate dispatch", async () => {
    vi.useFakeTimers();
    const t = convexTest(schema, modules);
    for (const component of ["orgNodeCountByType", "orgNodeCountByWorkspace", "orgNodeCountByParent"]) aggregateTest.register(t, component);
    const accountId = await t.run(async ctx => {
      const now = Date.now();
      const schoolId = await ctx.db.insert("schools", {
        name: "S11 delete fixture", slug: "s11-delete", verifiedDomains: [], status: "active",
        timezone: "UTC", policyVersion: 1, createdAt: now, updatedAt: now,
      });
      const id = await ctx.db.insert("accounts", {
        clerkId: identity.subject, email: identity.email, emailVerified: true, name: "Reader",
        status: "active", createdAt: now, updatedAt: now,
      });
      await ctx.db.insert("schoolMemberships", {
        accountId: id, schoolId, role: "student", status: "active", joinedAt: now, createdAt: now, updatedAt: now,
      });
      return id;
    });
    const user = t.withIdentity(identity);
    const workspaceId = await user.mutation(api.spectraWorkspaces.create, { title: "Disposable workspace" });
    const workspaceNode = await t.run(ctx => findPrimaryNode(ctx, accountId, "workspace", workspaceId));
    const children: Array<FunctionReturnType<typeof api.orgTree.createFolder>> = [];
    for (let index = 0; index < 21; index++) children.push(await user.mutation(api.orgTree.createFolder, {
      name: `Retained child ${index}`, parentId: workspaceNode!._id,
    }));
    const begin = () => user.mutation(api.spectraWorkspaces.permanentlyDelete, {
      workspaceId, confirmation: "Remove Disposable workspace permanently",
    });
    const deletion = await begin();
    expect((await begin()).jobId).toBe(deletion.jobId);
    const job = () => t.run(ctx => ctx.db.get(deletion.jobId));
    const advance = () => t.mutation(internal.spectraWorkspaces.continuePermanentDelete, { workspaceId, jobId: deletion.jobId });
    for (let step = 0; step < 10 && (await job())?.phase !== "move_children"; step++) await advance();
    expect((await job())?.phase).toBe("move_children");
    await advance();
    expect(await job()).toMatchObject({ phase: "move_children", movedChildCount: 20 });
    expect(await t.run(ctx => ctx.db.get(workspaceId))).not.toBeNull();
    // Resume scheduled work after the persisted partial move, including the
    // duplicate dispatch generated by retrying the original delete request.
    await t.finishAllScheduledFunctions(vi.runAllTimers);
    expect(await job()).toMatchObject({ phase: "complete", movedChildCount: 21 });
    expect(await t.run(ctx => ctx.db.get(workspaceId))).toBeNull();
    const retained = await t.run(async ctx => Promise.all(children.map(child => ctx.db.get(child.nodeId))));
    expect(retained.every(node => node !== null && node.deletedAt === undefined)).toBe(true);
    expect(new Set(retained.map(node => node!.parentId)).size).toBe(1);
    expect(retained[0]!.parentId).not.toBe(workspaceNode!._id);
    const general = await t.run(ctx => ctx.db.get(retained[0]!.workspaceContextId!));
    expect(general?.starterKey).toBe("general");
    await advance();
    expect(await job()).toMatchObject({ phase: "complete", movedChildCount: 21 });
  });
});
