#!/usr/bin/env node
/**
 * Bundles Spectra AI skills (src/features/spectra/ai/skills/<name>/SKILL.md plus resources) into
 * a generated TypeScript module, so the server reads them from the build and never from the
 * filesystem at runtime (Vercel functions do not ship these files).
 *
 *   node scripts/bundle-skills.mjs          write the bundle
 *   node scripts/bundle-skills.mjs --check  fail when the bundle is stale (prebuild, CI)
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SKILLS_DIR = "src/features/spectra/ai/skills";
export const BUNDLE_PATH = `${SKILLS_DIR}/bundle.generated.ts`;
/** Readable resources: reference text the model may load. Licences and notices stay on disk. */
const RESOURCE_EXTENSIONS = /\.(md|txt|json|csv)$/i;
const NOT_RESOURCES = /^(SKILL\.md|LICENSE.*|NOTICE.*)$/i;
const MAX_DESCRIPTION = 160;
const MAX_BODY = 24_000;
const MAX_RESOURCE = 40_000;

const lf = (text) => text.replace(/\r\n?/g, "\n");

/** `--- name: x / description: y ---` front matter, then the body. */
export function parseSkill(source, where) {
  const text = lf(source);
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text);
  if (!match) throw new Error(`${where}: SKILL.md must start with --- front matter ---.`);
  const fields = {};
  for (const line of match[1].split("\n")) {
    if (!line.trim()) continue;
    const field = /^([a-z][a-z-]*):\s*(.*)$/.exec(line);
    if (!field) throw new Error(`${where}: front matter line "${line}" is not "key: value".`);
    fields[field[1]] = field[2].trim().replace(/^"(.*)"$/, "$1");
  }
  return { fields, body: match[2].trim() };
}

function files(dir) {
  return readdirSync(dir)
    .flatMap((entry) => {
      const path = join(dir, entry);
      return statSync(path).isDirectory() ? files(path) : [path];
    })
    .sort();
}

export function collectSkills(root = process.cwd()) {
  const base = join(root, SKILLS_DIR);
  const skills = [];
  for (const folder of readdirSync(base).sort()) {
    const dir = join(base, folder);
    if (!statSync(dir).isDirectory()) continue;
    const skillFile = join(dir, "SKILL.md");
    if (!existsSync(skillFile)) throw new Error(`${folder}: every skill folder needs a SKILL.md.`);
    const { fields, body } = parseSkill(readFileSync(skillFile, "utf8"), `${folder}/SKILL.md`);
    if (fields.name !== folder) throw new Error(`${folder}/SKILL.md: name must be "${folder}", the folder name.`);
    const description = fields.description ?? "";
    if (!description || description.length > MAX_DESCRIPTION)
      throw new Error(`${folder}/SKILL.md: description must be one line of 1–${MAX_DESCRIPTION} characters.`);
    if (body.length > MAX_BODY) throw new Error(`${folder}/SKILL.md: body is over ${MAX_BODY} characters.`);
    const resources = files(dir)
      .map((path) => relative(dir, path).split("\\").join("/"))
      .filter((path) => RESOURCE_EXTENSIONS.test(path) && !NOT_RESOURCES.test(path.split("/").pop()))
      .map((path) => {
        const content = lf(readFileSync(join(dir, path), "utf8")).trim();
        if (content.length > MAX_RESOURCE) throw new Error(`${folder}/${path}: over ${MAX_RESOURCE} characters.`);
        return { path, content };
      });
    skills.push({ name: folder, description, body, resources });
  }
  return skills;
}

export function renderBundle(skills) {
  return [
    "// Generated by scripts/bundle-skills.mjs from src/features/spectra/ai/skills/*/SKILL.md.",
    "// Do not edit: change the skill folders and run `node scripts/bundle-skills.mjs`.",
    "",
    'import type { BundledSkill } from "./types";',
    "",
    `export const SKILL_BUNDLE: readonly BundledSkill[] = ${JSON.stringify(skills, null, 2)};`,
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const next = renderBundle(collectSkills());
  const current = existsSync(BUNDLE_PATH) ? lf(readFileSync(BUNDLE_PATH, "utf8")) : "";
  if (check) {
    if (current !== next) {
      console.error(`${BUNDLE_PATH} is out of date. Run: node scripts/bundle-skills.mjs`);
      process.exit(1);
    }
    console.log("Skills bundle is current.");
    return;
  }
  if (current !== next) writeFileSync(BUNDLE_PATH, next);
  console.log(`Bundled ${collectSkills().length} skills into ${BUNDLE_PATH}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
