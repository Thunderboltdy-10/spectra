/**
 * Bundles the syllabi in shared/syllabus/subjects/*.md into a generated
 * TypeScript module, so the AI's read_syllabus tool (Next) and the Syllabus
 * artifact a workspace starts with (Convex) both read the same build-time copy
 * and never the filesystem.
 *
 *   npx tsx scripts/bundle-syllabus.ts          write the bundle
 *   npx tsx scripts/bundle-syllabus.ts --check  fail when the bundle is stale (prebuild, CI)
 *
 * shared/syllabus/README.md describes the file format.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { outlineOf } from "../shared/syllabus/levels";
import type { BundledSyllabus, SyllabusLevel } from "../shared/syllabus/types";

const SUBJECTS_DIR = "shared/syllabus/subjects";
const BUNDLE_PATH = "shared/syllabus/bundle.generated.ts";
const CATALOG_PATH = "shared/syllabus/catalog.generated.ts";
const MAX_FILE = 200_000;
const LEVELS: readonly SyllabusLevel[] = ["SL", "HL"];

const lf = (text: string) => text.replace(/\r\n?/g, "\n");

function parse(source: string, where: string) {
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(lf(source));
  if (!match) throw new Error(`${where}: start with --- front matter ---.`);
  const fields: Record<string, string> = {};
  for (const line of match[1]!.split("\n")) {
    if (!line.trim()) continue;
    const field = /^([a-z][a-z-]*):\s*(.*)$/.exec(line);
    if (!field) throw new Error(`${where}: front matter line "${line}" is not "key: value".`);
    fields[field[1]!] = field[2]!.trim().replace(/^"(.*)"$/, "$1");
  }
  return { fields, body: match[2]!.trim() };
}

const list = (value: string | undefined) =>
  (value ?? "")
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);

export function collectSyllabi(root = process.cwd()): BundledSyllabus[] {
  const dir = join(root, SUBJECTS_DIR);
  if (!existsSync(dir)) return [];
  const seen = new Set<string>();
  return readdirSync(dir)
    .filter((file) => file.endsWith(".md") && !file.startsWith("_"))
    .sort()
    .map((file) => {
      const where = `${SUBJECTS_DIR}/${file}`;
      const source = readFileSync(join(dir, file), "utf8");
      if (source.length > MAX_FILE) throw new Error(`${where}: over ${MAX_FILE} characters.`);
      const { fields, body } = parse(source, where);
      const id = fields.id ?? file.replace(/\.md$/, "");
      if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) throw new Error(`${where}: id must be lowercase letters, digits and dashes.`);
      if (id !== file.replace(/\.md$/, "")) throw new Error(`${where}: id "${id}" must match the file name.`);
      if (seen.has(id)) throw new Error(`${where}: id "${id}" is used twice.`);
      seen.add(id);
      if (!fields.title) throw new Error(`${where}: needs a title.`);
      if (!body) throw new Error(`${where}: the outline is empty.`);
      const levels = list(fields.levels).map((level) => level.toUpperCase());
      for (const level of levels)
        if (!LEVELS.includes(level as SyllabusLevel)) throw new Error(`${where}: levels may only be SL and HL.`);
      return {
        id,
        title: fields.title,
        programme: fields.programme || "IB Diploma Programme",
        ...(fields.group ? { group: fields.group } : {}),
        levels: [...new Set(levels)] as SyllabusLevel[],
        ...(fields["first-assessment"] ? { firstAssessment: fields["first-assessment"] } : {}),
        ...(fields["last-assessment"] ? { lastAssessment: fields["last-assessment"] } : {}),
        ...(fields.source ? { source: fields.source } : {}),
        match: [...new Set([fields.title, ...list(fields.match)].map((term) => term.toLowerCase()))],
        version: createHash("sha256").update(lf(source)).digest("hex").slice(0, 16),
        sections: outlineOf(body),
        markdown: body,
      };
    });
}

export function renderBundle(syllabi: BundledSyllabus[]) {
  return [
    "// Generated by scripts/bundle-syllabus.ts from shared/syllabus/subjects/*.md.",
    "// Do not edit: change the subject files and run `npm run syllabus:bundle`.",
    "",
    'import type { BundledSyllabus } from "./types";',
    "",
    `export const SYLLABUS_BUNDLE: readonly BundledSyllabus[] = ${JSON.stringify(syllabi, null, 2)};`,
    "",
  ].join("\n");
}

/**
 * The small half: one hash over every syllabus (so a class sync can tell cheaply
 * that nothing changed) and the list a picker shows, without any outline text.
 */
export function renderCatalog(syllabi: BundledSyllabus[]) {
  const all = createHash("sha256")
    .update(syllabi.map((entry) => `${entry.id}:${entry.version}`).join("\n"))
    .digest("hex")
    .slice(0, 16);
  const catalog = syllabi.map((entry) => ({
    id: entry.id,
    title: entry.title,
    ...(entry.group ? { group: entry.group } : {}),
    levels: entry.levels,
  }));
  return [
    "// Generated by scripts/bundle-syllabus.ts. Do not edit.",
    "",
    'import type { SyllabusLevel } from "./types";',
    "",
    `export const SYLLABUS_BUNDLE_VERSION = ${JSON.stringify(syllabi.length ? all : "none")};`,
    "",
    `export const SYLLABUS_CATALOG: ReadonlyArray<{ id: string; title: string; group?: string; levels: SyllabusLevel[] }> = ${JSON.stringify(catalog, null, 2)};`,
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const syllabi = collectSyllabi();
  const outputs = [
    [BUNDLE_PATH, renderBundle(syllabi)],
    [CATALOG_PATH, renderCatalog(syllabi)],
  ] as const;
  const stale = outputs.filter(([path, next]) => (existsSync(path) ? lf(readFileSync(path, "utf8")) : "") !== next);
  if (check) {
    if (stale.length) {
      console.error(`${stale.map(([path]) => path).join(", ")} out of date. Run: npm run syllabus:bundle`);
      process.exit(1);
    }
    console.log("Syllabus bundle is current.");
    return;
  }
  for (const [path, next] of stale) writeFileSync(path, next);
  console.log(`Bundled ${syllabi.length} syllabi into ${BUNDLE_PATH}.`);
}

if (/bundle-syllabus\.[cm]?[jt]s$/.test(process.argv[1] ?? "")) main();
