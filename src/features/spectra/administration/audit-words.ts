function sentence(value: string) {
  return value.replaceAll(/[._]/g, " ").replace(/^\w/, (letter) => letter.toUpperCase());
}

export function auditActionWords(action: string) {
  return ACTIONS[action] ?? sentence(action);
}

export function auditTargetWords(targetType: string) {
  return TARGETS[targetType] ?? sentence(targetType);
}
