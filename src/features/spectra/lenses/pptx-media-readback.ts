import type { PresentationObject } from "../presentation/model";
import type { PptxProjection } from "./projection-contracts";

const nativeImageLocators = new Set(["nativeShapeId", "nativeParagraphIndex", "nativeShapeKind", "nativeMediaPart", "nativeMediaType"]);
const record = (value: unknown): Record<string, unknown> => value && typeof value === "object" && !Array.isArray(value) ? value as Record<string, unknown> : {};

function ordered(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(ordered);
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).sort(([left], [right]) => left.localeCompare(right)).map(([key, entry]) => [key, ordered(entry)]));
  return value;
}

/** Asset-backed pictures compare actual byte hashes and every authored field.
 * Package locators are generated by the writer; integer EMUs are the native
 * precision for geometry. Unknown content and style fields stay in the digest. */
export function pptxImageReadbackObject(object: PresentationObject, index: number, binding: PptxProjection["nativeBinding"]): PresentationObject {
  const content = record(object.content);
  if (object.type !== "image" || typeof content.assetId !== "string" || typeof content.sha256 !== "string") return object;
  const primary = Object.fromEntries(Object.entries(content).filter(([key, value]) =>
    !nativeImageLocators.has(key) && !(key === "text" && value === "") && !(key === "paragraphs" && Array.isArray(value) && !value.length),
  ));
  const emuPerUnit = (binding.canvasWidthEmu ?? 12192000) / 1000;
  return ordered({
    ...object,
    x: Math.round(object.x * emuPerUnit), y: Math.round(object.y * emuPerUnit),
    width: Math.round(object.width * emuPerUnit), height: Math.round(object.height * emuPerUnit),
    rotation: Math.round(object.rotation * 60000),
    content: ordered(primary),
    locked: Boolean(object.locked), hidden: Boolean(object.hidden),
    altText: object.altText ?? "", readingOrder: object.readingOrder ?? index,
  }) as PresentationObject;
}
